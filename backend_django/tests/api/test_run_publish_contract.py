"""Server half of the run-publish contract.

Every other test in ``test_run_publish.py`` hand-builds its payload with local
helpers, so they all encode what the endpoint was *intended* to accept. The client
produced something different, and nothing noticed: statuses arrived as bare ints,
action events lost ``action_type`` / ``action_data`` / ``success`` / …, and event
``category`` — which ``create()`` dispatches on — was absent.

This test posts the payload the ADARE client actually emits. The fixture
``tests/fixtures/run_publish_payload.json`` is generated by the client's
``adare/tests/unit/adare/database/test_serialize.py`` and both repos hold a
byte-identical copy; that test fails if the two drift.

If this test starts failing after a client change, the client changed the wire
format — regenerate the fixture on the client side and copy it here, or fix the
client.
"""

import json
from pathlib import Path

import pytest

from experiments.models import ActionEvent, ExperimentRun, TestEvent
from tests.factories import (
    AbstractTestFactory,
    EnvironmentFactory,
    ExperimentFactory,
)

CONTRACT_FIXTURE = Path(__file__).resolve().parents[1] / 'fixtures' / 'run_publish_payload.json'

PUBLISH_URL = '/api/run/publish/'


@pytest.fixture
def client_payload():
    return json.loads(CONTRACT_FIXTURE.read_text())


@pytest.fixture
def prerequisites(db, gitea_user, client_payload):
    """Experiment / environment / test carrying the ULIDs the payload references.

    The payload names the *remote* (server) ULIDs, which is the whole point: a
    client publishing a run refers to entities by the identity the server gave
    them, never by its own local ids.
    """
    env = EnvironmentFactory(published_by=gitea_user, ulid=client_payload['environment_ulid'])
    test_event = next(e for e in client_payload['events'] if e['event_type'] == 'test_event')
    abstract_test = AbstractTestFactory(ulid=test_event['abstract_test_ulid'])
    experiment = ExperimentFactory(
        published_by=gitea_user,
        ulid=client_payload['experiment_ulid'],
        environments=[env],
        abstract_tests=[abstract_test],
    )
    return {'experiment': experiment, 'environment': env, 'abstract_test': abstract_test}


@pytest.mark.django_db
class TestClientPayloadIsAccepted:

    def test_publish_succeeds(self, authenticated_client, prerequisites, client_payload):
        response = authenticated_client.post(
            PUBLISH_URL,
            data={'metadata': json.dumps(client_payload)},
            format='multipart',
        )
        assert response.status_code == 201, response.data

    def test_run_is_stored_with_the_payloads_statuses(self, authenticated_client,
                                                      prerequisites, client_payload):
        authenticated_client.post(
            PUBLISH_URL,
            data={'metadata': json.dumps(client_payload)},
            format='multipart',
        )
        run = ExperimentRun.objects.get(ulid=client_payload['ulid'])
        assert run.status.name == client_payload['status']
        assert run.result_status.name == client_payload['result_status']
        assert run.experiment.ulid == client_payload['experiment_ulid']
        assert run.environment.ulid == client_payload['environment_ulid']
        assert run.content_hash == client_payload['content_hash']

    def test_action_event_content_survives_the_round_trip(self, authenticated_client,
                                                         prerequisites, client_payload):
        authenticated_client.post(
            PUBLISH_URL,
            data={'metadata': json.dumps(client_payload)},
            format='multipart',
        )
        sent = next(e for e in client_payload['events'] if e['event_type'] == 'action_event')
        stored = ActionEvent.objects.get(ulid=sent['ulid'])
        assert stored.category == sent['category']
        assert stored.action_type == sent['action_type']
        assert stored.action_id == sent['action_id']
        assert stored.action_data == sent['action_data']
        assert stored.success is sent['success']
        assert stored.event_group_id == sent['event_group_id']
        assert stored.execution_time == sent['execution_time']
        assert stored.event_type_specific == sent['event_type_specific']

    def test_test_event_links_its_abstract_test_and_result(self, authenticated_client,
                                                          prerequisites, client_payload):
        authenticated_client.post(
            PUBLISH_URL,
            data={'metadata': json.dumps(client_payload)},
            format='multipart',
        )
        sent = next(e for e in client_payload['events'] if e['event_type'] == 'test_event')
        stored = TestEvent.objects.get(ulid=sent['ulid'])
        assert stored.abstracttest.ulid == sent['abstract_test_ulid']
        assert stored.result.status.name == sent['result']['status']
        assert stored.result.details == sent['result']['details']

    def test_content_hash_makes_a_reupload_a_conflict(self, authenticated_client,
                                                     prerequisites, client_payload):
        """The client now sends content_hash, so dedup is live rather than dead."""
        first = authenticated_client.post(
            PUBLISH_URL,
            data={'metadata': json.dumps(client_payload)},
            format='multipart',
        )
        assert first.status_code == 201

        duplicate = dict(client_payload, ulid='01JQRUNDUPLICATE0000000000')
        duplicate['events'] = []
        response = authenticated_client.post(
            PUBLISH_URL,
            data={'metadata': json.dumps(duplicate)},
            format='multipart',
        )
        assert response.status_code == 409, response.data
        assert response.data['existing_ulid'] == client_payload['ulid']


@pytest.mark.django_db
class TestContractAssumptions:
    """Guard the specific shapes the client relies on, so a server-side change
    that breaks them fails here rather than in a user's publish."""

    def test_statuses_in_payload_exist_as_status_rows(self, db, client_payload):
        from experiments.models import Status

        names = {client_payload['status'], client_payload['result_status']}
        names.update(e['result']['status'] for e in client_payload['events'] if 'result' in e)
        for name in names:
            assert Status.objects.filter(name=name).exists(), name

    def test_every_event_category_has_a_serializer(self, client_payload):
        from experiments.serializers import get_event_serializer

        for event in client_payload['events']:
            assert get_event_serializer(event['category']) is not None
