from django.conf import settings
import requests
from giteaeventmanager.exception import GiteaAuthException

DEFAULT_SCOPES = [
    "read:repository",
    "read:user",
]


class GiteaAuth:
    user: str = settings.GITEA_API_USER
    password: str = settings.GITEA_API_PASSWORD
    token_name: str = 'django_adare'

    generate_token_url = url = f'{settings.GITEA_API}users/{settings.GITEA_API_USER}/tokens'

    token = None
    token_scopes = [
        "read:repository",
        "read:user",
    ]

    def __init__(self):
        pass

    def generate_token(self):
        # check if token is already generated by requesting the token list
        resp = requests.get(self.generate_token_url, auth=(self.user, self.password))
        if resp.status_code == 200:
            for token in resp.json():
                if token['name'] == self.token_name:
                    self.destroy_token()
        else:
            raise GiteaAuthException(f'could not get token list: {resp.text} ({resp.status_code})')

        data = {
            "name": self.token_name,
            "scopes": self.token_scopes
        }
        response = requests.post(self.generate_token_url, json=data, auth=(self.user, self.password))
        if response.status_code != 201:
            raise GiteaAuthException(f'could not generate token: {response.text} ({response.status_code})')
        self.token = response.json()['sha1']

    def get_token(self, scopes: list = None):
        recreate_token = False
        if scopes:
            if set(scopes) != set(self.token_scopes):
                self.token_scopes = scopes
                recreate_token = True
        if recreate_token:
            self.destroy_token()
        if not self.token or recreate_token:
            self.generate_token()
        return self.token

    def destroy_token(self):
        resp = requests.delete(f'{self.generate_token_url}/{self.token_name}', auth=(self.user, self.password))
        if resp.status_code != 204:
            raise GiteaAuthException(f'could not delete token: {resp.text} ({resp.status_code})')
        self.token = None
        self.token_scopes = DEFAULT_SCOPES


GiteaAuthHandle = GiteaAuth()
